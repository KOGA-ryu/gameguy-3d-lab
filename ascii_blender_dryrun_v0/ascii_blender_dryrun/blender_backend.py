            "def petal_scroll_path_points(scroll, loc):",
            "    scroll_type = scroll.get('type', 'volute')",
            "    if scroll_type != 'volute':",
            "        raise ValueError(f'Unsupported petal scroll type: {scroll_type!r}')",
            "    samples = max(3, int(scroll.get('samples', 28)))",
            "    turns = float(scroll.get('turns', 0.9))",
            "    radius_start = float(scroll.get('radius_start', 0.9))",
            "    radius_end = float(scroll.get('radius_end', 0.18))",
            "    vertical_lift = float(scroll.get('vertical_lift', 0.45))",
            "    start_angle = math.radians(float(scroll.get('start_angle_deg', -100.0)))",
            "    direction = -1.0 if scroll.get('direction', 'ccw') == 'cw' else 1.0",
            "    points = []",
            "    for index in range(samples):",
            "        t = index / max(1, samples - 1)",
            "        radius = radius_start + (radius_end - radius_start) * t",
            "        angle = start_angle + direction * math.tau * turns * t",
            "        points.append({'t': t, 'x': loc[0] + math.cos(angle) * radius, 'y': loc[1], 'z': loc[2] + vertical_lift * t + math.sin(angle) * radius})",
            "    return points",
            "",
            "def petal_scroll_surface_point(petal, scroll, path, index, side, shell):",
            "    point = path[index]",
            "    previous = path[max(0, index - 1)]",
            "    next_point = path[min(len(path) - 1, index + 1)]",
            "    tx = next_point['x'] - previous['x']",
            "    tz = next_point['z'] - previous['z']",
            "    length = max(1e-9, math.hypot(tx, tz))",
            "    tx /= length",
            "    tz /= length",
            "    nx = -tz",
            "    nz = tx",
            "    t = point['t']",
            "    width = petal_width_at(petal, t)",
            "    thickness = petal_thickness_at(petal, t)",
            "    twist = math.radians(float(scroll.get('twist_deg', 0.0))) * t",
            "    width_x = nx * math.cos(twist) + tx * math.sin(twist)",
            "    width_z = nz * math.cos(twist) + tz * math.sin(twist)",
            "    side_offset = side * width * 0.5",
            "    relief_depth = float(scroll.get('relief_depth', 0.06))",
            "    curl_depth = float(scroll.get('curl_depth', 0.12)) * (abs(side) ** 1.7) * (t ** 1.1)",
            "    x = point['x'] + width_x * side_offset",
            "    y = point['y'] + relief_depth + curl_depth + shell * thickness * 0.5",
            "    z = point['z'] + width_z * side_offset",
            "    return x, y, z",
            "",
            "def add_petal_scroll_solid_fill(name, petal, scroll, path, loc, material):",
            "    fill = scroll.get('solid_fill')",
            "    if not fill or not fill.get('enabled', True):",
            "        return None",
            "    mode = fill.get('mode', 'center_fan')",
            "    if mode != 'center_fan':",
            "        raise ValueError(f'Unsupported petal scroll fill mode: {mode!r}')",
            "    front_y = loc[1] + float(fill.get('front_depth', 0.04))",
            "    back_y = loc[1] - float(fill.get('back_depth', 0.03))",
            "    center_x = loc[0]",
            "    center_z = loc[2] + float(scroll.get('vertical_lift', 0.45)) * 0.55",
            "    boundary = []",
            "    for index in range(len(path)):",
            "        neg = petal_scroll_surface_point(petal, scroll, path, index, -1.0, 0.0)",
            "        pos = petal_scroll_surface_point(petal, scroll, path, index, 1.0, 0.0)",
            "        neg_dist = math.hypot(neg[0] - center_x, neg[2] - center_z)",
            "        pos_dist = math.hypot(pos[0] - center_x, pos[2] - center_z)",
            "        pick = neg if neg_dist >= pos_dist else pos",
            "        boundary.append((pick[0], pick[2]))",
            "    verts = [(center_x, front_y, center_z)]",
            "    verts.extend((x, front_y, z) for x, z in boundary)",
            "    back_center_index = len(verts)",
            "    verts.append((center_x, back_y, center_z))",
            "    back_start = len(verts)",
            "    verts.extend((x, back_y, z) for x, z in boundary)",
            "    faces = []",
            "    count = len(boundary)",
            "    for index in range(count - 1):",
            "        nxt = index + 1",
            "        faces.append([0, index + 1, nxt + 1])",
            "        faces.append([back_center_index, back_start + nxt, back_start + index])",
            "        faces.append([index + 1, back_start + index, back_start + nxt, nxt + 1])",
            "    mesh = bpy.data.meshes.new(name + '_mesh')",
            "    mesh.from_pydata(verts, [], faces)",
            "    mesh.update(calc_edges=True)",
            "    obj = bpy.data.objects.new(name, mesh)",
            "    bpy.context.collection.objects.link(obj)",
            "    assign_mat(obj, fill.get('material', material))",
            "    if 'edge_bevel' in fill:",
            "        bevel(obj, float(fill['edge_bevel']), 1)",
            "    return obj",
            "",
