            "    length = float(petal['length']) * float(layer.get('length_scale', 1.0))",
            "    width = petal_width_at(petal, t) * float(layer.get('width_scale', 1.0))",
            "    thickness = petal_thickness_at(petal, t) * float(layer.get('thickness_scale', 1.0))",
            "    angle_base = math.radians(float(layer.get('spiral_offset_deg', 0.0))) + math.tau * petal_index / count",
            "    angle = angle_base + math.radians(float(layer.get('petal_twist_deg', 0.0))) * t",
            "    radial_x = math.cos(angle)",
            "    radial_y = math.sin(angle)",
            "    tangent_x = -radial_y",
            "    tangent_y = radial_x",
            "    bend_start = float(petal.get('bend_start_t', 0.45))",
            "    bend_t = max(0.0, (t - bend_start) / max(1e-9, 1.0 - bend_start))",
            "    bend_angle = math.radians(float(layer.get('bend_angle_deg', 0.0)))",
            "    bend_height = math.sin(bend_angle) * length * 0.42 * (bend_t ** 1.35)",
            "    bend_pull = (1.0 - math.cos(bend_angle * bend_t)) * length * 0.12",
            "    distance = radius + length * t - bend_pull",
            "    side_offset = side * width * 0.5",
            "    curl_angle = math.radians(abs(float(layer.get('curl_angle_deg', 0.0))))",
            "    curl_height = math.sin(curl_angle) * width * 0.24 * (abs(side) ** 1.7) * (t ** 1.25)",
            "    x = loc[0] + radial_x * distance + tangent_x * side_offset",
            "    y = loc[1] + radial_y * distance + tangent_y * side_offset",
            "    z = loc[2] + float(layer.get('z_offset', 0.0)) + bend_height + curl_height + thickness * 0.5 + z_lift",
            "    return x, y, z",
